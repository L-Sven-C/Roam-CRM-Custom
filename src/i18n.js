export function getUILanguage(extensionAPI) {
    const value = extensionAPI?.settings?.get(UI_LANGUAGE_SETTING_KEY)
    if (value === "中文" || value === "zh" || value === "zh-CN") return "zh"
    return "en"
}

export function t(extensionAPI, key, params = {}) {
    const language = getUILanguage(extensionAPI)
    const template = language === "zh" ? ZH[key] || EN[key] : EN[key]
    if (!template) return key

    return Object.entries(params).reduce(
        (result, [paramKey, value]) => result.replaceAll(`{${paramKey}}`, value),
        template,
    )
}
